# 发现问题：
# 问题	              表现	                    根本原因
# 长度不可控	      有时一两句话，有时一整段	没告诉模型摘要该多长
# 格式不统一	      有时是段落，有时是列表	没指定输出结构
# 语气随机	          有时口语化，有时偏书面	没设定角色或语气
# 遗漏关键信息	        摘要丢掉了原文的某些要点	指令太模糊，模型自行取舍


# 总结：
# 零样本提示能快速验证"模型是否理解了任务"，但无法保证输出质量和一致性。真实工程中，零样本适合做原型验证和快速探索，不适合直接上线。接下来我们逐步给它加约束。
