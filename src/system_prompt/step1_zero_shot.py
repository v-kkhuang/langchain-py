from dotenv import load_dotenv
from langchain_openai import ChatOpenAI
import os

load_dotenv()
llm = ChatOpenAI(
    model=os.environ["DEEPSEEK_MODEL"],  # 真实模型名
    base_url=os.environ["DEEPSEEK_API_URL"],
    api_key=os.environ["DEEPSEEK_API_KEY"],  # 手动传 key（因为变量名不是 OPENAI_API_KEY）
)


# 零样本（Zero-shot）指的是：prompt 中不包含任何输入-输出示例，仅靠一条自然语言指令告诉模型该做什么。模型完全依赖自身预训练知识来理解任务
# 这是最简单的调用方式，也最容易暴露问题——你会发现不给约束时，模型输出的摘要长度、格式、风格都不稳定。这种"不稳定"正是后面几步要解决的东西。
def summarize_zero_shot(text: str) -> str:
    """零样本摘要：最简单的指令，没有任何示例或约束"""
    prompt = f"请总结以下文本：\n\n {text}"
    response = llm.invoke(
        [
            {"role": "user", "content": prompt},
        ]
    )
    return response.content


sample_text = """
人工智能（AI）是计算机科学的一个分支，致力于创造能够模拟人类智能行为的系统。
近年来，深度学习技术的突破使得AI在图像识别、自然语言处理、语音识别等领域取得了显著进展。
然而，AI的发展也带来了伦理挑战，包括隐私保护、算法偏见、就业影响等问题。
专家认为，未来AI的发展需要在技术创新和伦理约束之间找到平衡。
"""


result = summarize_zero_shot(sample_text)
print("=== 零样本摘要 ===")
print(result)


